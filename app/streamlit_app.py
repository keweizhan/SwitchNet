# ── audio path resolution ──────────────────────────────────────────────────────

def _resolve_audio_path(audio_path: str) -> Optional[Path]:
    """Resolve an audio path to a local file using four strategies.

    Strategy 1 — direct: ``Path(audio_path).exists()``.
    Strategy 2 — data/ anchor (forward slash): normalise separators, find
                  the first ``data/`` segment and rebuild from repo root.
    Strategy 3 — data\\ anchor (Windows back-slash): same search with ``\\``.
    Strategy 4 — ``SWITCHNET_DATA_ROOT`` env var: replace the leading prefix
                  up to the first ``data`` component.

    Returns the resolved ``Path`` on the first hit, or ``None`` if not found.
    """
    p = Path(audio_path)
    if p.exists():
        return p

    norm = audio_path.replace("\\", "/")
    for anchor in ("data/",):
        idx = norm.find(anchor)
        if idx != -1:
            rel = norm[idx:]
            candidate = ROOT / Path(rel)
            if candidate.exists():
                return candidate

    data_root = os.environ.get("SWITCHNET_DATA_ROOT")
    if data_root:
        idx = norm.find("data/")
        if idx != -1:
            rel = norm[idx:]
            candidate = Path(data_root) / Path(rel)
            if candidate.exists():
                return candidate

    return None

