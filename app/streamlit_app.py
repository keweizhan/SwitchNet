@st.cache_data(show_spinner=False)
def _audio_wav_bytes(audio_path: str) -> Optional[bytes]:
    """Decode any audio (opus / flac / wav) → WAV bytes at native sample rate."""
    try:
        import librosa
        import soundfile as sf
        resolved = _resolve_audio_path(audio_path)
        if resolved is None:
            return None
        y, sr = librosa.load(str(resolved), sr=None, mono=True)
        buf = io.BytesIO()
        sf.write(buf, y, sr, format="WAV")
        return buf.getvalue()
    except Exception:
        return None


@st.cache_data(show_spinner=False)
def _load_jsonl(path: str) -> Dict[str, dict]:
    """Load eval JSONL → {entry_id: record}."""
    records: Dict[str, dict] = {}
    try:
        with open(path, encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                if not line:
                    continue
                r = json.loads(line)
                records[r["id"]] = r
    except Exception:
        pass
    return records


@st.cache_data(show_spinner=False)
def _load_summary(path: str) -> Optional[dict]:
    try:
        with open(path, encoding="utf-8") as f:
            return json.load(f)
    except Exception:
        return None


@st.cache_data(show_spinner=False)
def _summary_from_jsonl(jsonl_path: str) -> Optional[dict]:
    """Compute a summary dict from a results JSONL when no *_summary.json exists.

    Uses ``evaluate_results`` from src.asr.evaluate — same logic as the eval
    scripts, so WER/MER numbers are consistent.  Returns None on any error.
    """
    try:
        from src.asr.evaluate import evaluate_results
        return evaluate_results(results_path=jsonl_path, output_path=None)
    except Exception:
        return None


@st.cache_data(show_spinner=False)
def _audio_duration(audio_path: str) -> float:
    """Return duration in seconds; falls back to 5.0 on error."""
    try:
        import librosa
        resolved = _resolve_audio_path(audio_path)
        if resolved is None:
            return 5.0
        return float(librosa.get_duration(path=str(resolved)))
    except Exception:
        return 5.0


